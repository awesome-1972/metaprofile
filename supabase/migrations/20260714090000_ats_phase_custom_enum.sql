-- ============================================================
-- ATS: Гнучка воронка — крок 1/2 (enum, окрема транзакція)
-- ============================================================
-- Щоб дозволити ДОВІЛЬНІ етапи пошуку під запит (а не лише 6 фіксованих),
-- розширюємо enum значенням 'custom'. ALTER TYPE ADD VALUE не можна виконувати
-- в одній транзакції з подальшим використанням значення — тому enum окремою
-- міграцією перед тією, що ним користується (як у 20260710090000).
--
-- Семантика: kind лишається машинним ключем для спецлогіки (preparation →
-- панель артефактів; longlist → імпорт Excel; шаблони листів по kind). Кастомні
-- етапи мають kind='custom' — звичайна воронка без спецлогіки; назва довільна.
-- ============================================================

alter type public.search_phase_kind add value if not exists 'custom';
