-- ============================================================
-- Редагована шкала рівнів відповідності (оцінка компетенцій)
-- ============================================================
-- Пороги «висока/середня/низька» тепер налаштовує користувач на вакансії, а не
-- хардкод. competency_scale jsonb: { "high": 2.5, "medium": 2.0 } (шкала 1–3).
-- null → дефолт у коді. Використовує Edge generate-candidate-report і UI матриці.
-- ============================================================

alter table public.vacancies
  add column if not exists competency_scale jsonb;

comment on column public.vacancies.competency_scale is
  'Редаговані пороги рівнів відповідності: {"high":2.5,"medium":2.0} (шкала 1–3). null → дефолт у коді.';
