-- ============================================================
-- ATS: Гнучка воронка — крок 2/2 (колір етапу + унікальність позицій)
-- ============================================================
-- Візуальний поділ наскрізної воронки: колір етапу. Наскрізний вигляд показує
-- усі стадії всіх етапів одним рядом, а етапи розрізняються кольором заголовка.
-- color nullable — якщо не заданий, клієнт бере детермінований колір за position.
--
-- Гнучке налаштування (додавання/видалення етапів і стадій) НЕ потребує нових
-- таблиць: search_phases і pipeline_stages вже мають RLS під mp_can_edit_vacancy,
-- а guard mp_pipeline_stage_delete_guard захищає від видалення стадії з
-- кандидатами. Тут лише колонка кольору.
-- ============================================================

alter table public.search_phases
  add column if not exists color text;

comment on column public.search_phases.color is
  'HEX-колір заголовка етапу в наскрізній воронці (напр. #6366f1). '
  'NULL → клієнт бере колір із палітри за позицією.';
