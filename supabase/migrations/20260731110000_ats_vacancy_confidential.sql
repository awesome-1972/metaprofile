-- ============================================================
-- Конфіденційний пошук: прапорець на вакансії
-- ============================================================
-- Ставиться на етапі «Підготовка». Увімкнено → назву клієнта НЕ показувати
-- кандидатам: у бріфі (disclose_client=false), у листах, на job-порталі та в
-- публічному посиланні. Внутрішні користувачі клієнта бачать (робота ведеться).
-- ============================================================

alter table public.vacancies
  add column if not exists is_confidential boolean not null default false;

comment on column public.vacancies.is_confidential is
  'Конфіденційний пошук: назву клієнта не показувати кандидатам (бріф/листи/портал). '
  'Ставиться на етапі Підготовки; керує disclose_client при генерації бріфу.';
